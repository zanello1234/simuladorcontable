import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { viteSingleFile } from 'vite-plugin-singlefile';

// `npm run build:single` genera un único index.html autocontenido (para publicar como Artifact
// o mandarlo por mail/WhatsApp y jugarlo desde cualquier dispositivo).
export default defineConfig(({ mode }) => ({
  base: './',
  plugins: [react(), ...(mode === 'single' ? [viteSingleFile()] : [])],
  build: { outDir: mode === 'single' ? 'dist-single' : 'dist', chunkSizeWarningLimit: 1200 },
  test: { globals: true, environment: 'node' },
}));
